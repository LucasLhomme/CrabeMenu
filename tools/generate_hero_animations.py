"""Builds modules/hero_animations_data.lua: which biped animation events each playable hero can play.

An event branches to animation tree states; a state plays a named clip, or picks one of its default
branches. A hero can play the event when its .bent motion bank defines at least one of those clips.
Vanilla banks live in the decrypted knowledge base; mod heroes are resolved in game from their loose .bent.
"""
import argparse
import re
import sys
from pathlib import Path

GAME = Path(r"D:\SteamLibrary\steamapps\common\Disney Infinity 3.0 Gold Edition\assets")
KB = Path(r"E:\Dev\DIM2\research\knowledge-base\decypted\characters")
OUT = Path(__file__).resolve().parent.parent / "modules" / "hero_animations_data.lua"

STATE_RE = re.compile(r'<AnimTreeState name="([^"]+)"')
CLIP_RE = re.compile(r'<p:Clip value="([^"]*)"')
BRANCH_RE = re.compile(r'<AnimTreeBranch\b[^>]*>(.*?)</AnimTreeBranch>', re.S)
BRANCH_TO_RE = re.compile(r'<p:BranchTo value="([^"]+)"')
DEFAULT_RE = re.compile(r'<p:DefaultBranch value="TRUE"')
EVENT_RE = re.compile(r'AnimTreeEventPointerProperty" value="([^"]+)"')
TOKEN_RE = re.compile(rb"[A-Za-z0-9_]{3,}")


def tree_files():
    """Returns the biped project and every animtree it can include."""
    chars = GAME / "characters"
    return [chars / "biped" / "biped.animtreeproject"] + sorted(chars.glob("biped/*.animtree")) + \
        sorted(chars.glob("animtree_includes/*.animtree"))


def parse_tree():
    """Returns state -> (clips, default targets) and event -> branch targets over all tree files."""
    states, events = {}, {}
    for path in tree_files():
        text = path.read_text(encoding="latin-1")
        marks = [(m.start(), m.group(1)) for m in STATE_RE.finditer(text)]
        for index, (start, name) in enumerate(marks):
            end = marks[index + 1][0] if index + 1 < len(marks) else len(text)
            body = text[start:end]
            clips, defaults = states.setdefault(name, (set(), set()))
            clip = CLIP_RE.search(body)
            if clip and clip.group(1):
                clips.add(clip.group(1))
            for branch in BRANCH_RE.finditer(body):
                if DEFAULT_RE.search(branch.group(1)):
                    defaults.update(BRANCH_TO_RE.findall(branch.group(1)))
        for branch in BRANCH_RE.finditer(text):
            targets = BRANCH_TO_RE.findall(branch.group(1))
            for event in EVENT_RE.findall(branch.group(1)):
                events.setdefault(event, set()).update(targets)
    return states, events


def clip_closure(targets, states):
    """Returns every clip the target states can play, following default branches."""
    clips, seen, todo = set(), set(), list(targets)
    while todo:
        name = todo.pop()
        if name in seen or name not in states:
            continue
        seen.add(name)
        own, defaults = states[name]
        clips |= own
        todo.extend(defaults)
    return clips


def hero_names():
    """Returns the catalog names of every playable hero (rows with a progression tree)."""
    text = (GAME / "presentation" / "virtualreaderpc_data.lua").read_text(encoding="latin-1")
    data = text[text.index("AvatarData"):]
    names = []
    for block in re.findall(r"\{([^{}]*)\}", data):
        name = re.search(r'Name\s*=\s*"([^"]+)"', block)
        if name and re.search(r'ProgressionTree\s*=\s*"[^"]+"', block):
            names.append(name.group(1))
    return names


def bent_index():
    """Maps lowercase bank names to their .bent files in the knowledge base."""
    return {p.stem.lower(): p for p in KB.rglob("*.bent")}


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()

    states, branch_events = parse_tree()
    event_clips = {e: clip_closure(t, states) for e, t in branch_events.items()}
    event_clips = {e: c for e, c in event_clips.items() if c}
    events = sorted(event_clips, key=str.lower)
    banks = bent_index()

    heroes, missing = {}, []
    for name in hero_names():
        bent = banks.get(name.lower())
        if not bent:
            missing.append(name)
            continue
        tokens = {t.decode() for t in TOKEN_RE.findall(bent.read_bytes())}
        bits = 0
        for index, event in enumerate(events):
            if event_clips[event] & tokens:
                bits |= 1 << index
        heroes[name] = format(bits, "x")

    lines = ["-- Generated by tools/generate_hero_animations.py; do not edit.", "return {", "    events = {"]
    lines += ["        %s," % lua_string(e) for e in events]
    lines += ["    },", "    clips = {"]
    lines += ["        { %s }," % ", ".join(lua_string(c) for c in sorted(event_clips[e])) for e in events]
    lines += ["    },", "    heroes = {"]
    lines += ["        [%s] = %s," % (lua_string(h), lua_string(b)) for h, b in sorted(heroes.items())]
    lines += ["    },", "}", ""]
    args.out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(events)} events with clips, {len(heroes)} heroes, no bank for: {', '.join(missing) or 'none'}")
    print(f"wrote {args.out} ({args.out.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
